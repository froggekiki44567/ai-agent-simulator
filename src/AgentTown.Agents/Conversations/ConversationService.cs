using AgentTown.Agents.Loop;
using AgentTown.Agents.State;
using AgentTown.Contracts.Events;
using AgentTown.Llm.Conversations;
using AgentTown.Llm.Scheduling;
using Microsoft.Extensions.Logging;

namespace AgentTown.Agents.Conversations;

public sealed class ConversationOptions
{
    public const string SectionName = "Agents:Conversations";

    /// <summary>A conversation is not ended early before this many lines (unless the LLM fails).</summary>
    public int MinLines { get; set; } = 2;

    /// <summary>A conversation never has more than this many lines.</summary>
    public int MaxLines { get; set; } = 4;
}

/// <summary>Where and when a conversation happens.</summary>
public sealed record ConversationScene(long Tick, int Day, int Hour, int Minute, string? PlaceId);

/// <summary>What came out of a conversation (used later for memories and relationships).</summary>
/// <param name="Agreement">Something both agreed on, e.g. "meet at the cafe tomorrow", or null.</param>
/// <param name="InitiatorTone">Average tone (-5..5) of the initiator's lines towards the partner.</param>
/// <param name="PartnerTone">Average tone (-5..5) of the partner's lines towards the initiator.</param>
/// <param name="EndReason">Why it stopped before <see cref="ConversationOptions.MaxLines"/>, or null.</param>
public sealed record ConversationOutcome(
    Guid ConversationId,
    Guid InitiatorId,
    Guid PartnerId,
    IReadOnlyList<ConversationMessage> Lines,
    string? Agreement,
    double InitiatorTone,
    double PartnerTone,
    string? EndReason);

/// <summary>
/// Runs a conversation of 2–4 lines between two agents. Speakers take turns; each line is generated by
/// the LLM from the speaker's point of view, using both personalities. Every line is published as
/// <see cref="ConversationMessage"/>, the last one with <c>IsFinal = true</c>.
/// Each line uses one call from the LLM budget. If the LLM fails, the conversation ends with the lines it has.
/// </summary>
public sealed class ConversationService(
    LlmScheduler scheduler,
    ConversationPromptBuilder prompts,
    ConversationReplyParser parser,
    IAgentEventPublisher publisher,
    ConversationOptions options,
    ILogger<ConversationService> logger)
{
    /// <param name="openingLine">What the initiator already said in its <c>Talk</c> action (line 0), if anything.</param>
    public async Task<ConversationOutcome> RunAsync(
        AgentState initiator,
        AgentState partner,
        string? openingLine,
        ConversationScene scene,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(initiator);
        ArgumentNullException.ThrowIfNull(partner);
        ArgumentNullException.ThrowIfNull(scene);

        var maxLines = Math.Max(1, options.MaxLines);
        var minLines = Math.Clamp(options.MinLines, 1, maxLines);

        var lines = new List<(AgentState Speaker, string Text)>();
        var tones = new Dictionary<Guid, List<int>> { [initiator.Id] = [], [partner.Id] = [] };
        string? agreement = null;
        string? endReason = null;

        if (!string.IsNullOrWhiteSpace(openingLine))
            lines.Add((initiator, Truncate(openingLine.Trim())));

        while (lines.Count < maxLines)
        {
            var speaker = lines.Count % 2 == 0 ? initiator : partner;
            var listener = speaker == initiator ? partner : initiator;

            var prompt = prompts.Build(new ConversationPromptContext
            {
                Speaker = ToParticipant(speaker),
                Listener = ToParticipant(listener),
                History = lines.Select(l => new ConversationLine(l.Speaker.Name, l.Text)).ToArray(),
                PlaceId = scene.PlaceId,
                Day = scene.Day,
                Hour = scene.Hour,
                Minute = scene.Minute,
                IsLastLine = lines.Count == maxLines - 1,
            });

            var call = await scheduler.RequestAsync(prompt, cancellationToken);
            if (!call.Success)
            {
                endReason = call.Failure.ToString();
                break;
            }

            var parsed = parser.Parse(call.Text);
            if (!parsed.Success)
            {
                endReason = $"InvalidResponse: {parsed.Error}";
                break;
            }

            var reply = parsed.Reply!;
            lines.Add((speaker, reply.Say));
            tones[speaker.Id].Add(reply.Tone);
            agreement = reply.Agreement ?? agreement;

            if (reply.End && lines.Count >= minLines)
            {
                endReason = "Ended";
                break;
            }
        }

        if (endReason is not null and not "Ended")
            logger.LogInformation("Conversation {Initiator} → {Partner} stopped after {Count} lines: {Reason}",
                initiator.Name, partner.Name, lines.Count, endReason);

        var conversationId = Guid.NewGuid();
        var messages = lines.Select((line, index) => new ConversationMessage(
            conversationId,
            line.Speaker.Id,
            line.Speaker == initiator ? partner.Id : initiator.Id,
            line.Text,
            index,
            IsFinal: index == lines.Count - 1)).ToArray();

        foreach (var message in messages)
            await publisher.PublishConversationAsync(message, scene.Tick, cancellationToken);

        return new ConversationOutcome(conversationId, initiator.Id, partner.Id, messages, agreement,
            Average(tones[initiator.Id]), Average(tones[partner.Id]), endReason);
    }

    private static ConversationParticipant ToParticipant(AgentState agent) =>
        new(agent.Name, agent.Age, agent.Personality.Traits, agent.Personality.Goal, agent.Personality.SpeakingStyle);

    private static double Average(List<int> values) => values.Count == 0 ? 0 : values.Average();

    private static string Truncate(string text) =>
        text.Length <= ConversationReplyParser.MaxSayLength ? text : text[..ConversationReplyParser.MaxSayLength];
}
